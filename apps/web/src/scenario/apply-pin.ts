import type { AssumeEntry, Json, ScenarioInput, Unknown } from '@simulci/engine';
import { draftFor, type PinContext, type PinDraft } from '../panels/pin-draft';
import type { FieldFocus } from '../state/store';

/**
 * What an unknown's row offers (synthesis § 7's table), and the pure edits a pin makes: a scenario fragment merged
 * into the scenario, an assume entry added to or removed from the case layer. The UI never invents a fragment for a
 * scenario unknown: it applies whichever one the unknown carries.
 */

export type PinControl =
  /** A scenario field pins it (`pin.layer === 'scenario'`, or an input's expression default): Set … naming the field. */
  | { kind: 'scenario'; label: string; fragment: Record<string, Json>; focus: Omit<FieldFocus, 'seq'> }
  /** An assume entry the engine wrote pins it (the fail-fast race): Assume cancelled. */
  | { kind: 'assume'; label: string; entry: AssumeEntry }
  /** A step or job output, outcome or env write the engine has no pin for: Pin… opens the PinEditor, prefilled. */
  | { kind: 'editor'; label: string; draft: PinDraft }
  /** Nothing the author writes pins it: the unknown's `gap`, or "only the run decides it" (generate.ts's words). */
  | { kind: 'none'; text: string };

/** What a test case generated by the engine says of an unknown nothing pins. */
const NO_PIN = 'only the run decides it';
const CONFIG_PIN = 'set in the config layer, which the web app does not read';

/** `inputs.<name>.default`: an input whose default is an expression, which only the run evaluates. */
const EXPRESSION_DEFAULT = /^inputs\.(.+)\.default$/;

/** The control for an unknown's row. */
export function pinControl(unknown: Unknown, ctx: PinContext): PinControl {
  const { pin } = unknown;
  if (pin?.layer === 'config') return { kind: 'none', text: unknown.gap ?? CONFIG_PIN };
  if (pin?.layer === 'scenario' && isRecord(pin.fragment)) return scenarioControl(pin.fragment);
  if (pin?.layer === 'assume' && isRecord(pin.fragment) && namesUnit(pin.fragment)) {
    const entry = pin.fragment as AssumeEntry;
    return { kind: 'assume', label: assumeLabel(entry), entry };
  }
  const input = pin ? undefined : EXPRESSION_DEFAULT.exec(unknown.id)?.[1];
  if (input !== undefined) return scenarioControl({ inputs: { [input]: '' } });
  const draft = draftFor(unknown, ctx);
  if (draft) return { kind: 'editor', label: 'Pin…', draft };
  return { kind: 'none', text: unknown.gap ?? NO_PIN };
}

function scenarioControl(fragment: Record<string, Json>): PinControl {
  return { kind: 'scenario', label: scenarioLabel(fragment), fragment, focus: pinFocus(fragment) };
}

const namesUnit = (fragment: Record<string, Json>): boolean =>
  typeof fragment.job === 'string' || typeof fragment.step === 'string';

function assumeLabel(entry: AssumeEntry): string {
  return entry.outcome === undefined ? 'Add the assumption' : `Assume ${entry.outcome}`;
}

/** The field a scenario fragment writes, as its button names it. */
const FIELD_LABELS = new Map([
  ['changed', 'Set changed files'],
  ['action', 'Set the activity type'],
  ['sha', 'Set the commit SHA'],
  ['actor', 'Set the actor'],
  ['repository', 'Set the repository'],
  ['tag', 'Set the tag'],
  ['branch', 'Set the branch'],
  ['ref', 'Set the ref'],
]);

const WORKFLOW_RUN_LABELS = new Map([
  ['name', 'Set the triggering workflow'],
  ['branch', 'Set its branch'],
]);

/** The fields named by the entry under them: the variable, the input, the triggering run's key. */
const ENTRY_LABELS = new Map<string, (entry: string | undefined) => string | undefined>([
  ['vars', (name) => (name === undefined ? undefined : `Set vars.${name}`)],
  ['inputs', (name) => (name === undefined ? undefined : `Set input ${name}`)],
  ['workflow_run', (key) => WORKFLOW_RUN_LABELS.get(key ?? '') ?? 'Set the triggering run'],
]);

function scenarioLabel(fragment: Record<string, Json>): string {
  const [key, value] = Object.entries(fragment)[0] ?? [];
  if (key === undefined) return 'Set the scenario';
  return ENTRY_LABELS.get(key)?.(firstKey(value)) ?? FIELD_LABELS.get(key) ?? `Set ${key}`;
}

/** The keys replaced together: a fragment that names one of them drops the others, as the test runner does. */
const REF_GROUP = new Set(['ref', 'branch', 'tag']);
/** The records merged key by key. */
const MERGED = new Set(['inputs', 'vars', 'actor']);

/**
 * The scenario with a pin's fragment merged as the test runner merges `when` over `given` (engine
 * test/runner.ts `mergeScenario`): `inputs`, `vars` and `actor` key by key, the ref group (`ref`, `branch`, `tag`)
 * replaced whole when the fragment names any of it, anything else replaced. `keys` are the top-level keys written,
 * for the assumed marks.
 */
export function applyScenarioPin(
  scenario: ScenarioInput,
  fragment: Record<string, Json>,
): { scenario: ScenarioInput; keys: string[] } {
  const written = Object.entries(fragment);
  const ref = written.some(([key]) => REF_GROUP.has(key));
  const out = new Map<string, unknown>(
    Object.entries(scenario).filter(([key]) => !(ref && REF_GROUP.has(key))),
  );
  for (const [key, value] of written) {
    const base = out.get(key);
    out.set(key, MERGED.has(key) && isRecord(base) && isRecord(value) ? merged(base, value) : value);
  }
  return { scenario: Object.fromEntries(out) as ScenarioInput, keys: written.map(([key]) => key) };
}

/** Two records as one, the second's keys over the first's; author keys stay data (a `__proto__` key included). */
const merged = (base: Record<string, unknown>, over: Record<string, unknown>): Record<string, unknown> =>
  Object.fromEntries([...Object.entries(base), ...Object.entries(over)]);

/**
 * The field a fragment writes, as an issue-style path the form resolves (`vars` with the variable as `entry`,
 * `inputs.<name>`, `actor.login`, `workflow_run.<key>`, `changed`, `action`, `tag`, `sha`, `repository`).
 */
export function pinFocus(fragment: Record<string, Json>): Omit<FieldFocus, 'seq'> {
  const [key, value] = Object.entries(fragment)[0] ?? [];
  if (key === undefined) return { path: '' };
  const sub = firstKey(value);
  if (key === 'vars') return sub === undefined ? { path: 'vars' } : { path: 'vars', entry: sub };
  if (key === 'actor') return { path: 'actor.login' };
  if ((key === 'inputs' || key === 'workflow_run') && sub !== undefined) return { path: `${key}.${sub}` };
  return { path: key };
}

/** The case layer with an entry added at the end, or put in place of the entry at `at`. */
export function withEntry(assume: readonly AssumeEntry[], entry: AssumeEntry, at?: number): AssumeEntry[] {
  if (at === undefined || at < 0 || at >= assume.length) return [...assume, entry];
  return assume.map((e, i) => (i === at ? entry : e));
}

/** The case layer without the entry at `at`. */
export function withoutEntry(assume: readonly AssumeEntry[], at: number): AssumeEntry[] {
  return assume.filter((_, i) => i !== at);
}

/** The first key of a record; undefined for anything else. */
const firstKey = (value: Json | undefined): string | undefined =>
  isRecord(value) ? Object.keys(value)[0] : undefined;

function isRecord(value: unknown): value is Record<string, Json> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}
